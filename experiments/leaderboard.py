"""Collect runs/exp/*/result.json into experiments/LEADERBOARD.md (sorted by val loss).

    python -m experiments.leaderboard
"""

import json

from experiments.common import ROOT, RUNS


def main():
    rows = []
    for p in sorted(RUNS.glob("*/result.json")):
        rows.append(json.loads(p.read_text()))
    running = [p.name for p in RUNS.iterdir()
               if p.is_dir() and not (p / "result.json").exists()]
    rows.sort(key=lambda r: r["val_loss"])
    hdr = ("| id | name | params | val loss | test loss | test rmse_sph | test top30 | "
           "test top10 | test beam gain dB | test beam pt deg | nb3-unseen top30 | stop @ step | min |")
    lines = ["# Leaderboard", "",
             "Auto-generated by `python -m experiments.leaderboard`. Sorted by val loss "
             "(weighted L1 dB, same as training loss `l1db`). rmse_sph = full-sphere RMSE; "
             "topN = RMSE over pixels within N dB of the peak.", "", hdr,
             "|" + "---|" * (hdr.count("|") - 1)]
    for r in rows:
        t = r["test"]["all"]
        un = f"{r['unseen']['all']['rmse_top30db']:.3f}" if "unseen" in r else ""
        lines.append(
            f"| {r['id']} | {r['name']} | {r['params']:,} | {r['val_loss']:.4f} | "
            f"{r['test']['loss']:.4f} | {t['rmse_sphere_db']:.2f} | {t['rmse_top30db']:.3f} | "
            f"{t['rmse_top10db']:.3f} | {t['beam_gain_err_db']:.3f} | "
            f"{t['beam_point_err_deg']:.3f} | {un} | {r['stop']} @ {r['best_step']} | "
            f"{r['minutes']:.0f} |")
    lines += ["", "## Descriptions", ""] + [f"- **{r['id']}** {r['desc']}" for r in
                                            sorted(rows, key=lambda r: r["id"])]
    if running:
        lines += ["", "Unfinished / running: " + ", ".join(sorted(running))]
    (ROOT / "experiments" / "LEADERBOARD.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[4:4 + len(rows) + 2]))


if __name__ == "__main__":
    main()
